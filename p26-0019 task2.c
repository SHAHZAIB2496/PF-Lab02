#include <stdio.h>

int main()
{
    printf("================ C ESCAPE SEQUENCES REFERENCE ================\n");

    printf("To print a double quote, write:\t\t \\\" \n");
    printf("To print a literal backslash, write:\t \\\\ \n");
    printf("To insert a newline break, write:\t \\n \n");
    printf("To insert a horizontal tab stop, write:\t \\t \n");
    printf("To print a percent sign, write:\t\t %%%%\n");


    printf("==============================================================\n");

    return 0;
}